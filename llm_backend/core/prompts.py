import json

from schemas.ai import ModelMetadata


DESCRIPTION_SYSTEM_PROMPT = (
    "你是一个 3D 资产管理专家。"
    "上传模型固定带有封面图，你必须优先根据封面图中真实可见的主体、颜色、形态、材质、风格和可能用途生成描述。"
    "同时结合模型名称、分类、标签、用户简介和结构信息。"
    "如果图片信息与文字信息冲突，以封面图可见事实为准。"
    "不要编造无法从输入或图片判断的事实，无法判断的内容留空，不要猜测。"
    "请把封面图视觉信息写入 description、tags 和 search_text。"
    "输出必须是合法 JSON 对象，不要包含 Markdown。"
)


ANSWER_SYSTEM_PROMPT = (
    "你是本站 3D 模型平台的 AI 助手。"
    "你只能使用提供的站内模型资源回答问题。"
    "如果资料不足，必须说明限制。"
    "不要编造模型名称、作者、URL、标签或下载资源。"
)


def build_description_prompt(model: ModelMetadata) -> str:
    """构造上传模型描述生成提示词。"""

    return json.dumps(
        {
            "任务": "请观察这张 3D 模型的渲染封面图，并为模型生成适合入库检索的结构化描述。",
            "输出格式": {
                "description": "对模型全貌进行一段 100 字以内的中文自然语言描述，包括外观、主体身份、形态、服饰、姿态、颜色、材质或其他可见细节",
                "tags": {
                    "subject": ["主体对象，例如女性角色、长剑、跑车、草莓、建筑"],
                    "category": ["资源类别，例如角色、武器、载具、动物、植物、建筑、道具、场景"],
                    "style": ["艺术或制作风格，例如二次元、低多边形、写实、卡通、科幻"],
                    "features": ["关键视觉特征，例如金发、双马尾、机械臂、披风、红色果实"],
                    "color": ["主要颜色，例如红色、绿色、黑色、金色"],
                    "material": ["可见材质，例如金属、木质、布料、塑料、玻璃"],
                    "use_cases": ["适用场景，例如游戏道具、教学演示、场景装饰、角色资产"],
                },
                "search_text": "把 description 和 tags 中的信息组织成一段适合语义检索的中文自然语言，不要只堆叠关键词",
            },
            "要求": [
                "不要编造用户未提供或封面图无法判断的信息",
                "不要输出未知、待定、N/A 这类占位词；无法判断的字段返回空字符串或空数组",
                "上传模型固定有封面图时，必须优先结合封面图可见内容描述外观",
                "保留标题、分类、标签和用户简介中的有效信息",
                "tags 每个字段都必须是字符串数组，无法判断时返回空数组",
                "search_text 必须是自然语言段落，包含名称、主体、分类、外观、风格、用途和关键特征",
                "输出必须是合法 JSON 对象",
            ],
            "模型信息": model.model_dump(by_alias=True),
        },
        ensure_ascii=False,
    )


def build_answer_user_prompt(question: str, context: str) -> str:
    """构造 RAG 问答用户提示词。"""

    return (
        f"用户问题：\n{question}\n\n"
        f"站内检索资料：\n{context}\n\n"
        "请用中文回答，优先推荐最相关模型，并简要说明推荐理由。"
    )
